#!/usr/bin/env python3
"""Re-composite bubbles on existing pages WITHOUT re-rendering SDXL.

Requires pre-bubble snapshots at /tmp/v10-pNN-pre-bubble.png (generated by
composite_page since 2026-05-29). For pages that don't have a snapshot,
this script falls back to running full orchestrator.

Usage:
  python3 scripts/recompose-bubbles.py --pages 28,31,17 --prefix v11sk
"""
from __future__ import annotations
import argparse, importlib.util, json, os, sys
from pathlib import Path

LG = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pages", required=True, help="comma-separated page numbers")
    ap.add_argument("--prefix", default="v11sk",
                     help="output prefix in /tmp (e.g. v11sk → v11sk-pNN-scored.png)")
    ap.add_argument("--manifest",
                     default=str(LG.parent / "data/ghosthacker/resources/episodes/arc0-1-origin/image-gen-manifest.json"))
    args = ap.parse_args()

    pages = [int(p) for p in args.pages.split(",")]
    manifest = json.loads(Path(args.manifest).read_text())

    # Load render-v5 module
    spec = importlib.util.spec_from_file_location(
        "rv5", LG / "scripts/render-v5-page.py")
    rv5 = importlib.util.module_from_spec(spec); spec.loader.exec_module(rv5)

    # Load v11_layout for augmentation
    os.environ.setdefault("V11_LAYOUT", "1")
    from lg_mangaka import v11_layout as _v11lay

    from PIL import Image, ImageFilter

    for pg in pages:
        snap = Path(f"/tmp/v10-p{pg:02d}-pre-bubble.png")
        if not snap.exists():
            print(f"p{pg:02d}: NO SNAPSHOT — needs full render via orchestrator first")
            continue
        # Build layout
        panels = sorted([p for p in manifest["panels"] if p["pageNum"] == pg],
                         key=lambda p: p["panelIndex"])
        panels = _v11lay.augment_page(panels, pg)
        layout = rv5.compute_layout(panels)

        # Start from pre-bubble snapshot, redraw bubbles
        work = Path(f"/tmp/recompose-p{pg:02d}.png")
        Image.open(snap).save(work)
        rv5._draw_bubbles_on_image(work, layout)

        # Apply SMOOTH + UnsharpMask (same as orchestrator final)
        img = Image.open(work).filter(ImageFilter.SMOOTH).filter(
            ImageFilter.UnsharpMask(radius=1.5, percent=80, threshold=2))
        out = Path(f"/tmp/{args.prefix}-p{pg:02d}-scored.png")
        img.save(out)
        print(f"p{pg:02d}: recomposed → {out}")

    print("\nDone. Open in browser or use page-eval-ui.py to rate.")


if __name__ == "__main__":
    main()
